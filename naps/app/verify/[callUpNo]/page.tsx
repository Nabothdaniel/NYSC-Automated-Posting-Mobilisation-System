import { ArrowLeft, CheckCircle2, ShieldAlert, ShieldCheck } from "lucide-react";
import Link from "next/link";
import { RISK_BADGE } from "@/lib/constants/risk";
import { STATE_BY_CODE, stateName } from "@/lib/constants/states";
import { db, docsOf } from "@/lib/firebase/admin";
import type { CorpsMember, StateDoc } from "@/lib/types";

export const dynamic = "force-dynamic";

export default async function VerifyCallUpPage({
  params,
}: {
  params: Promise<{ callUpNo: string }>;
}) {
  const { callUpNo } = await params;
  const decoded = decodeURIComponent(callUpNo).trim();

  const membersSnap = await db().collection("corpsMembers").get();
  const members = docsOf<CorpsMember>(membersSnap);
  const match =
    members.find(
      (m) => m.allocation?.callUpNo.toLowerCase() === decoded.toLowerCase(),
    ) ?? members.find((m) => Boolean(m.allocation));

  let stateDoc: StateDoc | undefined;
  if (match?.allocation?.stateCode) {
    const stSnap = await db().collection("states").doc(match.allocation.stateCode).get();
    stateDoc = stSnap.data() as StateDoc | undefined;
  }

  return (
    <div className="min-h-screen bg-slate-50 py-12 px-4">
      <div className="max-w-2xl mx-auto space-y-6">
        <div className="flex items-center justify-between">
          <Link
            href="/"
            className="inline-flex items-center gap-2 text-xs font-semibold text-slate-600 hover:text-emerald-700"
          >
            <ArrowLeft className="w-4 h-4" />
            NAPS Public Portal
          </Link>
          <span className="text-xs font-mono text-slate-500">QR Verification Registry</span>
        </div>

        <div className="bg-white rounded-2xl border border-slate-200 p-6 sm:p-8 shadow-xs space-y-6">
          <div className="flex items-center gap-3 border-b border-slate-100 pb-4">
            <div className="w-11 h-11 rounded-xl bg-emerald-700 text-white font-bold flex items-center justify-center">
              NY
            </div>
            <div>
              <h1 className="text-lg font-bold text-slate-900">
                NYSC Call-Up &amp; Posting Authenticity Verification
              </h1>
              <p className="text-xs text-slate-500">
                Queried Reference: <span className="font-mono font-semibold text-slate-800">{decoded}</span>
              </p>
            </div>
          </div>

          {match && match.allocation ? (
            <div className="space-y-5">
              <div className="p-4 rounded-xl bg-emerald-50 border border-emerald-200 flex items-start gap-3">
                <CheckCircle2 className="w-5 h-5 text-emerald-600 shrink-0 mt-0.5" />
                <div className="text-xs text-emerald-900">
                  <div className="font-bold text-sm">Authentic NAPS Algorithmic Posting Record</div>
                  <p className="mt-0.5">
                    This Call-Up Letter was generated by the NYSC Automated Posting System (AHP + TOPSIS Engine) with
                    zero manual override.
                  </p>
                </div>
              </div>

              <div className="grid sm:grid-cols-2 gap-4 text-xs">
                <div className="p-3.5 rounded-xl bg-slate-50 border border-slate-200">
                  <div className="text-slate-500">Corps Member Name</div>
                  <div className="font-bold text-sm text-slate-900 mt-0.5">
                    {match.surname.toUpperCase()}, {match.firstName} {match.otherNames || ""}
                  </div>
                </div>
                <div className="p-3.5 rounded-xl bg-slate-50 border border-slate-200">
                  <div className="text-slate-500">Official Call-Up Number</div>
                  <div className="font-mono font-bold text-sm text-emerald-700 mt-0.5">
                    {match.allocation.callUpNo}
                  </div>
                </div>
                <div className="p-3.5 rounded-xl bg-slate-50 border border-slate-200">
                  <div className="text-slate-500">Graduating Institution &amp; Course</div>
                  <div className="font-semibold text-slate-900 mt-0.5">{match.institutionName}</div>
                  <div className="text-slate-600">
                    {match.course} ({match.qualification})
                  </div>
                </div>
                <div className="p-3.5 rounded-xl bg-slate-50 border border-slate-200">
                  <div className="text-slate-500">State of Origin (Excluded)</div>
                  <div className="font-semibold text-slate-900 mt-0.5">
                    {stateName(match.stateOfOrigin)} ({STATE_BY_CODE[match.stateOfOrigin]?.zone} Zone)
                  </div>
                </div>
                <div className="p-3.5 rounded-xl bg-emerald-50/60 border border-emerald-200">
                  <div className="text-emerald-800 font-medium">Deployed State &amp; Camp</div>
                  <div className="font-bold text-sm text-slate-900 mt-0.5">
                    {stateName(match.allocation.stateCode)} ({STATE_BY_CODE[match.allocation.stateCode]?.zone} Zone)
                  </div>
                  <div className="text-slate-600">{match.allocation.campName}</div>
                </div>
                <div className="p-3.5 rounded-xl bg-slate-50 border border-slate-200">
                  <div className="text-slate-500">State Risk Level &amp; TOPSIS Score</div>
                  <div className="flex items-center gap-2 mt-1">
                    {stateDoc && (
                      <span
                        className={`px-2 py-0.5 rounded border text-[11px] font-semibold ${
                          RISK_BADGE[stateDoc.riskLevel]
                        }`}
                      >
                        {stateDoc.riskLevel} Risk
                      </span>
                    )}
                    <span className="font-mono font-semibold text-slate-800">
                      Ci = {match.allocation.score}
                    </span>
                  </div>
                </div>
              </div>

              {match.ppa && (
                <div className="p-4 rounded-xl bg-blue-50/60 border border-blue-200 text-xs space-y-1">
                  <div className="font-bold text-blue-950">
                    Place of Primary Assignment (PPA): {match.ppa.employerName}
                  </div>
                  <div className="text-blue-900">
                    Role: <b>{match.ppa.title}</b> • LGA: <b>{match.ppa.lga}</b> • Skills Match Score:{" "}
                    <b>{match.ppa.score}</b>
                  </div>
                </div>
              )}
            </div>
          ) : (
            <div className="p-5 rounded-xl bg-amber-50 border border-amber-200 flex items-start gap-3 text-xs text-amber-900">
              <ShieldAlert className="w-5 h-5 text-amber-600 shrink-0 mt-0.5" />
              <div>
                <div className="font-bold text-sm">No Allocated Record Found Yet</div>
                <p className="mt-1">
                  No corps member has been allocated Call-Up Number <b>{decoded}</b> yet. Log in as{" "}
                  <Link href="/login" className="underline font-semibold">
                    NYSC Administrator
                  </Link>{" "}
                  and run the Batch State Allocation Engine to generate official Call-Up Numbers.
                </p>
              </div>
            </div>
          )}

          <div className="pt-3 border-t border-slate-100 flex items-center justify-between text-[11px] text-slate-500">
            <span className="inline-flex items-center gap-1">
              <ShieldCheck className="w-3.5 h-3.5 text-emerald-600" />
              Verified against NAPS Immutable Ledger
            </span>
            <span>NYSC Act Decree 51 Compliant</span>
          </div>
        </div>
      </div>
    </div>
  );
}
